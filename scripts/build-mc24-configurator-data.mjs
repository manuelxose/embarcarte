#!/usr/bin/env node
/**
 * MC-24 configurator projection generator.
 *
 * Reads `docs/marea/bundles/bundle-definitions.json` (MC-08) and writes
 * `src/app/marea-catalog/data/configurator.generated.ts`. Every question, rule
 * and conflict rule is transcribed verbatim; nothing is summarised or invented.
 *
 *   node scripts/build-mc24-configurator-data.mjs           write
 *   node scripts/build-mc24-configurator-data.mjs --check   fail on drift
 *
 * Read-only with respect to the contract. No network, no clock, no randomness.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTRACT = resolve(root, 'docs/marea/bundles/bundle-definitions.json');
const OUTPUT = resolve(root, 'src/app/marea-catalog/data/configurator.generated.ts');

const GROUP_ORDER = ['general', 'safetySensitive', 'b2bFleet'];
const GROUP_ID = { general: 'GENERAL', safetySensitive: 'SAFETY_SENSITIVE', b2bFleet: 'B2B_FLEET' };

function lit(value) {
  return JSON.stringify(value);
}

function build() {
  const contract = JSON.parse(readFileSync(CONTRACT, 'utf8'));

  const questionnaires = contract.eligibilityQuestionnaires;
  if (!questionnaires) throw new Error('contract has no eligibilityQuestionnaires');

  const questions = [];
  for (const key of GROUP_ORDER) {
    const group = questionnaires[key];
    if (!group) throw new Error(`missing questionnaire group ${key}`);
    const appliesTo = Array.isArray(group.appliesTo) && group.appliesTo.length > 0 ? group.appliesTo : null;
    for (const question of group.questions) {
      questions.push({
        id: question.id,
        group: GROUP_ID[key],
        question: question.question,
        appliesTo,
      });
    }
  }

  // The contract names the B2B questions by count only in some revisions; the
  // ids must come from the contract itself, never be invented here.
  const seen = new Set();
  for (const question of questions) {
    if (seen.has(question.id)) throw new Error(`duplicate question id ${question.id}`);
    seen.add(question.id);
  }

  const rules = (contract.configurationRules ?? []).map((rule) => ({
    id: rule.id,
    name: rule.name,
    scope: rule.scope,
    condition: rule.condition,
    outcome: rule.outcome,
    evidenceRequirement: rule.evidenceRequirement,
  }));

  const conflictRules = (contract.conflictRules ?? []).map((rule) => ({
    id: rule.id,
    name: rule.name,
    scope: rule.scope,
    condition: rule.condition,
    outcome: rule.outcome,
    message: rule.message,
  }));

  const outcomes = contract.configurationOutcomes ?? [];
  const inclusion = contract.inclusionVocabulary ?? [];

  const lines = [];
  lines.push('/**');
  lines.push(' * MC-24 configurator rule projection - GENERATED FROM THE MC-08 CONTRACT.');
  lines.push(' *');
  lines.push(' * Every questionnaire field, configuration rule and conflict rule below is');
  lines.push(' * transcribed from `docs/marea/bundles/bundle-definitions.json` (MC-08). Nothing');
  lines.push(' * is authored, summarised or invented. Regenerate with');
  lines.push(' * `node scripts/build-mc24-configurator-data.mjs`; `--check` fails when the two');
  lines.push(' * drift, so a hand edit that disagrees with the contract is a build error rather');
  lines.push(' * than a review decision. Do not edit this file by hand.');
  lines.push(' *');
  lines.push(' * Two boundaries that must never be misread:');
  lines.push(' *');
  lines.push(' *  1. These are CONFIGURATION rules, not compatibility evidence. A rule listed');
  lines.push(' *     here does not prove that any device is compatible; the MC-05 D5 matrix has');
  lines.push(' *     zero `TESTED` rows, so no validated rule set exists yet.');
  lines.push(' *  2. There is no `ORDERABLE` outcome here and none may be produced. Nothing in');
  lines.push(' *     this projection grants a sale, a price, a stock position or a quotation.');
  lines.push(' */');
  lines.push('');
  lines.push('export const CONFIGURATOR_QUESTION_GROUPS = [');
  lines.push(GROUP_ORDER.map((key) => `  ${lit(GROUP_ID[key])},`).join('\n'));
  lines.push('] as const;');
  lines.push('');
  lines.push('export type ConfiguratorQuestionGroup = (typeof CONFIGURATOR_QUESTION_GROUPS)[number];');
  lines.push('');
  lines.push('export interface ConfiguratorQuestion {');
  lines.push('  readonly id: string;');
  lines.push('  readonly group: ConfiguratorQuestionGroup;');
  lines.push('  readonly question: string;');
  lines.push('  /** Canonical bundles the group applies to; `null` means every bundle. */');
  lines.push('  readonly appliesTo: readonly string[] | null;');
  lines.push('}');
  lines.push('');
  lines.push(`/** The ${questions.length} canonical MC-08 eligibility questions, in contract order. */`);
  lines.push('export const CONFIGURATOR_QUESTIONS: readonly ConfiguratorQuestion[] = [');
  for (const question of questions) {
    lines.push(
      `  { id: ${lit(question.id)}, group: ${lit(question.group)}, question: ${lit(question.question)}, appliesTo: ${question.appliesTo === null ? 'null' : `[${question.appliesTo.map(lit).join(',')}]`} },`,
    );
  }
  lines.push('];');
  lines.push('');
  lines.push('export interface ConfiguratorRule {');
  lines.push('  readonly id: string;');
  lines.push('  readonly name: string;');
  lines.push('  readonly scope: string;');
  lines.push('  readonly condition: string;');
  lines.push('  readonly outcome: string;');
  lines.push('  readonly evidenceRequirement: string;');
  lines.push('}');
  lines.push('');
  lines.push(`/** The ${rules.length} canonical MC-08 configuration rules, in contract order. */`);
  lines.push('export const CONFIGURATOR_RULES: readonly ConfiguratorRule[] = [');
  for (const rule of rules) {
    lines.push(
      `  { id: ${lit(rule.id)}, name: ${lit(rule.name)}, scope: ${lit(rule.scope)}, condition: ${lit(rule.condition)}, outcome: ${lit(rule.outcome)}, evidenceRequirement: ${lit(rule.evidenceRequirement)} },`,
    );
  }
  lines.push('];');
  lines.push('');
  lines.push('export interface ConfiguratorConflictRule {');
  lines.push('  readonly id: string;');
  lines.push('  readonly name: string;');
  lines.push('  readonly scope: string;');
  lines.push('  readonly condition: string;');
  lines.push('  readonly outcome: string;');
  lines.push('  readonly message: string;');
  lines.push('}');
  lines.push('');
  lines.push(`/** The ${conflictRules.length} canonical MC-08 conflict rules, in contract order. */`);
  lines.push('export const CONFIGURATOR_CONFLICT_RULES: readonly ConfiguratorConflictRule[] = [');
  for (const rule of conflictRules) {
    lines.push(
      `  { id: ${lit(rule.id)}, name: ${lit(rule.name)}, scope: ${lit(rule.scope)}, condition: ${lit(rule.condition)}, outcome: ${lit(rule.outcome)}, message: ${lit(rule.message)} },`,
    );
  }
  lines.push('];');
  lines.push('');
  lines.push('/** MC-08 internal configuration outcomes. `ORDERABLE` deliberately does not exist. */');
  lines.push('export const CONFIGURATOR_CONTRACT_OUTCOMES = [');
  lines.push(outcomes.map((value) => `  ${lit(value)},`).join('\n'));
  lines.push('] as const;');
  lines.push('');
  lines.push('/** MC-08 inclusion vocabulary, for cross-checking contract-derived lines. */');
  lines.push('export const CONFIGURATOR_CONTRACT_INCLUSIONS = [');
  lines.push(inclusion.map((value) => `  ${lit(value)},`).join('\n'));
  lines.push('] as const;');
  lines.push('');
  lines.push('export const CONFIGURATOR_PROJECTION_META = {');
  lines.push(`  contractId: ${lit(contract.contractId)},`);
  lines.push(`  contractVersion: ${lit(contract.contractVersion)},`);
  lines.push(`  contractMilestone: ${lit(contract.milestone)},`);
  lines.push(`  questionCount: ${questions.length},`);
  lines.push(`  ruleCount: ${rules.length},`);
  lines.push(`  conflictRuleCount: ${conflictRules.length},`);
  lines.push('} as const;');
  lines.push('');

  return { text: lines.join('\n'), counts: { questions: questions.length, rules: rules.length, conflictRules: conflictRules.length } };
}

const { text, counts } = build();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    console.log(`FAIL mc24 configurator data - ${OUTPUT} does not exist; run without --check`);
    process.exit(1);
  }
  if (current !== text) {
    console.log('FAIL mc24 configurator data - generated projection has drifted from the MC-08 contract');
    process.exit(1);
  }
  console.log(
    `MC-24 configurator data: up to date (${counts.questions} questions, ${counts.rules} rules, ${counts.conflictRules} conflict rules)`,
  );
  process.exit(0);
}

writeFileSync(OUTPUT, text);
console.log(
  `MC-24 configurator data: wrote ${counts.questions} questions, ${counts.rules} rules, ${counts.conflictRules} conflict rules`,
);
