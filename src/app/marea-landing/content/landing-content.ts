const b = (
  sectionId: LandingSectionId,
  contentId: string,
  copyClass: CopyClass,
  sourceType: ContentSourceType,
  evidenceIds: readonly string[],
  es: string,
  en: string,
): ContentBlock => ({
  contentId,
  sectionId,
  sourceType,
  copyClass,
  evidenceIds,
  publicationStatus: PUBLICATION_STATUS,
  approvalStatus: APPROVAL_STATUS,
  text: { es, en },
});

const item = (itemId: string, title: ContentBlock, body: ContentBlock): ContentItem => ({
  itemId,
  title,
  body,
});

const nav = (id: string, href: string, es: string, en: string): NavigationEntry => ({
  id,
  href,
  label: { es, en },
});

const layer = (layerId: string, title: ContentBlock, body: ContentBlock): EcosystemLayer => ({
  layerId,
  title,
  body,
});

const family = (
  familyId: string,
  summary: ContentBlock,
  material: ContentBlock,
  commercial: ContentBlock,
): LandingFamilyCopy => ({
  familyId,
  summary,
  limitations: [material, commercial],
});

const bundle = (
  bundleId: string,
  summary: ContentBlock,
  first: ContentBlock,
  second: ContentBlock,
): LandingBundleCopy => ({
  bundleId,
  summary,
  constraints: [first, second],
});

const node = (
  nodeId: string,
  kind: ArchitectureNodeKind,
  label: ContentBlock,
): ArchitectureNode => ({ nodeId, kind, label });

const link = (linkId: string, from: string, to: string, label: ContentBlock): ArchitectureLink => ({
  linkId,
  from,
  to,
  nature: 'CONCEPTUAL_DEPENDENCY',
  label,
});

const dimension = (
  dimensionId: string,
  label: ContentBlock,
  note: ContentBlock | null = null,
): ReadinessDimensionCopy => ({ dimensionId, label, note });

