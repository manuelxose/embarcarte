/**
 * MC-18 internal landing — the ONE bilingual content source.
 *
 * Every rendered sentence of the isolated MAREA preview lives here as a typed
 * block with its provenance, copy class and fixed publication/approval state.
 * The landing is internal draft copy only: nothing in this file is approved
 * public copy and no block may be promoted by a build flag or environment
 * variable (the literals below match the frozen contract in `content.types`).
 *
 * ES is the default locale; EN is served alongside it. Both strings of a block
 * carry the same claim, the same caveats and the same negation.
 */

